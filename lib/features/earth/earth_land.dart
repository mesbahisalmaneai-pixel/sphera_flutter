import 'dart:typed_data';

/// Land / ocean mask of the Earth, used to build the dotted Earth hub.
///
/// It is a SIMPLIFIED world map: hand-built polygons of the coastlines
/// (about 1 degree accurate), so the dotted globe looks like the real Earth.
/// [earthIsLand] answers "is this point land?" for a latitude and longitude in
/// degrees. Inland seas and the Great Lakes are carved out of the land.
///
/// Polygon data is flat: lon, lat, lon, lat, ... Polygons that cross the date
/// line (eastern Russia) use longitudes above 180.
bool earthIsLand(double lat, double lon) {
  var x = lon;
  while (x < -180) {
    x += 360;
  }
  while (x >= 180) {
    x -= 360;
  }
  for (final s in _seas) {
    if (s.contains(x, lat)) {
      return false;
    }
  }
  for (final l in _lands) {
    if (l.contains(x, lat)) {
      return true;
    }
  }
  return false;
}

class _Poly {
  _Poly._(this.pts, this.minX, this.maxX, this.minY, this.maxY);

  factory _Poly(List<double> flat) {
    var minX = double.infinity, maxX = -double.infinity;
    var minY = double.infinity, maxY = -double.infinity;
    for (var i = 0; i < flat.length; i += 2) {
      final x = flat[i], y = flat[i + 1];
      if (x < minX) {
        minX = x;
      }
      if (x > maxX) {
        maxX = x;
      }
      if (y < minY) {
        minY = y;
      }
      if (y > maxY) {
        maxY = y;
      }
    }
    return _Poly._(Float64List.fromList(flat), minX, maxX, minY, maxY);
  }

  final Float64List pts;
  final double minX, maxX, minY, maxY;

  bool contains(double x, double y) {
    if (y < minY || y > maxY) {
      return false;
    }
    if (x >= minX && x <= maxX && _inside(x, y)) {
      return true;
    }
    // Polygons that cross the date line use longitudes above 180.
    final x2 = x + 360;
    return maxX > 180 && x2 >= minX && x2 <= maxX && _inside(x2, y);
  }

  bool _inside(double x, double y) {
    var inside = false;
    var j = pts.length - 2;
    for (var i = 0; i < pts.length; j = i, i += 2) {
      final xi = pts[i], yi = pts[i + 1], xj = pts[j], yj = pts[j + 1];
      if ((yi > y) != (yj > y) && x < (xj - xi) * (y - yi) / (yj - yi) + xi) {
        inside = !inside;
      }
    }
    return inside;
  }
}

